/**
 * 발행일과 최종 수정일.
 *
 * 원칙: 내용을 실제로 고치지 않았다면 날짜를 올리지 않는다. 내용 변경 없이 dateModified만
 * 갱신하는 것은 조작이며 감지되면 역효과다. 따라서 updated 필드가 없으면 date와 같은 값을
 * 반환하고, 실제로 글을 고칠 때에만 해당 가이드에 updated: "YYYY-MM-DD" 를 추가한다.
 *
 * 사이트맵 lastmod와 Article JSON-LD의 dateModified가 이 함수 하나를 공유하므로
 * 두 값은 영구히 일치한다.
 */
export function guideUpdated(guide) {
  return guide.updated || guide.date;
}

export function getGuide(slug) {
  return guides.find((g) => g.slug === slug);
}
